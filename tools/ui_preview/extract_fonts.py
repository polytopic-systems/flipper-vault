"""Pull the firmware's u8g2 fonts out of the uFBT SDK's firmware.elf.

The preview renders text with the exact font data the Flipper uses, without
committing the font bytes to this repo. Usage:

    python extract_fonts.py <firmware.elf> <out fonts.h>
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

FONTS = {
    "FontPrimary": "u8g2_font_helvB08_tr",
    "FontSecondary": "u8g2_font_haxrcorp4089_tr",
    "FontKeyboard": "u8g2_font_profont11_mr",
    "FontBigNumbers": "u8g2_font_profont22_tn",
}


def read_elf(path: Path) -> tuple[bytes, list[tuple[int, int, int]], dict[str, tuple[int, int]]]:
    data = path.read_bytes()
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
        raise SystemExit("expected a 32-bit little-endian ELF")
    (e_shoff,) = struct.unpack_from("<I", data, 0x20)
    e_shentsize, e_shnum, e_shstrndx = struct.unpack_from("<HHH", data, 0x2E)
    sections = []
    for i in range(e_shnum):
        sh = struct.unpack_from("<IIIIIIIIII", data, e_shoff + i * e_shentsize)
        sections.append(sh)
    # (name, type, flags, addr, offset, size, link, info, align, entsize)
    progbits = [(s[3], s[4], s[5]) for s in sections if s[1] == 1 and s[3] != 0]
    symbols: dict[str, tuple[int, int]] = {}
    for s in sections:
        if s[1] != 2:  # SHT_SYMTAB
            continue
        strtab = sections[s[6]]
        for off in range(s[4], s[4] + s[5], 16):
            name_off, value, size, _info, _other, _shndx = struct.unpack_from("<IIIBBH", data, off)
            start = strtab[4] + name_off
            end = data.index(b"\0", start)
            name = data[start:end].decode("ascii", "replace")
            if name.startswith("u8g2_font_") and size > 0:
                symbols[name] = (value, size)
    return data, progbits, symbols


def symbol_bytes(data: bytes, progbits, addr: int, size: int) -> bytes:
    for sec_addr, sec_off, sec_size in progbits:
        if sec_addr <= addr and addr + size <= sec_addr + sec_size:
            start = sec_off + (addr - sec_addr)
            return data[start : start + size]
    raise SystemExit(f"address {addr:#x} not in a loaded section")


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    data, progbits, symbols = read_elf(Path(sys.argv[1]))
    lines = ["/* Generated by extract_fonts.py from the uFBT SDK firmware.elf. Do not commit. */",
             "#pragma once", "#include <stdint.h>"]
    for font, sym in FONTS.items():
        if sym not in symbols:
            raise SystemExit(f"{sym} not found in firmware.elf")
        blob = symbol_bytes(data, progbits, *symbols[sym])
        body = ",".join(str(b) for b in blob)
        lines.append(f"static const uint8_t preview_{font}[{len(blob)}] = {{{body}}};")
    lines.append("static const uint8_t *const preview_fonts[4] = {preview_FontPrimary, "
                 "preview_FontSecondary, preview_FontKeyboard, preview_FontBigNumbers};")
    Path(sys.argv[2]).write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
